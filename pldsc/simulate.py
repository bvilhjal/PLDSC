"""Deterministic genotype simulators for PLDSC experiments (milestone M1).

Small, explicit generators used by the ``experiments/`` scripts and the test
suite. Each takes an explicit ``numpy.random.Generator`` and returns genotypes
together with the metadata needed to reproduce them. Local LD is generated by an
AR(1) Gaussian copula (exact marginal allele frequencies); population structure
by Balding-Nichols allele frequencies; relatedness by transmitting parental
haplotypes to full siblings.

These are simulators, not the estimator; nothing here makes a scientific claim.
"""
from __future__ import annotations

import numpy as np
from numpy.typing import NDArray

Float = NDArray[np.float64]


def ndtri(p: Float) -> Float:
    """Inverse standard-normal CDF (Acklam's rational approximation, ~1e-9)."""
    p = np.asarray(p, dtype=np.float64)
    a = [-3.969683028665376e01, 2.209460984245205e02, -2.759285104469687e02,
         1.383577518672690e02, -3.066479806614716e01, 2.506628277459239e00]
    b = [-5.447609879822406e01, 1.615858368580409e02, -1.556989798598866e02,
         6.680131188771972e01, -1.328068155288572e01]
    c = [-7.784894002430293e-03, -3.223964580411365e-01, -2.400758277161838e00,
         -2.549732539343734e00, 4.374664141464968e00, 2.938163982698783e00]
    d = [7.784695709041462e-03, 3.224671290700398e-01, 2.445134137142996e00,
         3.754408661907416e00]
    plow, phigh = 0.02425, 1 - 0.02425
    x = np.empty_like(p)
    lo, hi = p < plow, p > phigh
    mid = ~(lo | hi)
    if lo.any():
        q = np.sqrt(-2 * np.log(p[lo]))
        x[lo] = (((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q+c[5]) / \
                ((((d[0]*q+d[1])*q+d[2])*q+d[3])*q+1)
    if hi.any():
        q = np.sqrt(-2 * np.log(1 - p[hi]))
        x[hi] = -(((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q+c[5]) / \
                ((((d[0]*q+d[1])*q+d[2])*q+d[3])*q+1)
    q = p[mid] - 0.5
    r = q * q
    x[mid] = (((((a[0]*r+a[1])*r+a[2])*r+a[3])*r+a[4])*r+a[5])*q / \
             (((((b[0]*r+b[1])*r+b[2])*r+b[3])*r+b[4])*r+1)
    return x


def standardize(G: Float) -> Float:
    """Column-standardize a genotype matrix to mean 0, unit expected variance."""
    p = G.mean(0) / 2.0
    s = np.sqrt(2.0 * p * (1.0 - p))
    s = np.where(s == 0, 1.0, s)
    return (G - 2.0 * p) / s


def grm(G: Float) -> Float:
    """Standardized genetic relationship matrix ``Z Z^T / m``."""
    Z = standardize(G)
    return (Z @ Z.T) / Z.shape[1]


def bn_freqs(rng, m: int, fst: float) -> tuple[Float, Float]:
    """Balding-Nichols allele frequencies for two populations (fst apart)."""
    anc = rng.uniform(0.1, 0.9, size=m)
    a, b = anc * (1 - fst) / fst, (1 - anc) * (1 - fst) / fst
    return rng.beta(a, b), rng.beta(a, b)


def ar1_haps(rng, freqs_mat: Float, rho: float) -> Float:
    """``(n_hap, m)`` haplotypes: AR(1) latent LD, per-haplotype marginals."""
    freqs_mat = np.atleast_2d(freqs_mat)
    n_hap, m = freqs_mat.shape
    z = np.empty((n_hap, m))
    z[:, 0] = rng.standard_normal(n_hap)
    root = np.sqrt(1 - rho * rho)
    for s in range(1, m):
        z[:, s] = rho * z[:, s - 1] + root * rng.standard_normal(n_hap)
    return (z < ndtri(freqs_mat)).astype(np.float64)


def _positions(chrom_sizes, spacing_cm=0.15):
    chrom = np.concatenate([np.full(m, c) for c, m in enumerate(chrom_sizes)])
    pos = np.concatenate([np.arange(m) * spacing_cm for m in chrom_sizes])
    return chrom, pos


def _sib_genome(rng, phap, nchr):
    """One offspring: inherit one gamete from each parent, per chromosome."""
    return np.concatenate(
        [phap[c][rng.integers(2)] + phap[c][2 + rng.integers(2)]
         for c in range(nchr)]
    )


def simulate_relatedness(rng, chrom_sizes, n_fam, sibs, rho=0.6):
    """Homogeneous population, ``n_fam`` sibships of ``sibs`` full siblings.

    Returns ``(G, chrom, pos)``. Within-family pairs have GRM ~0.5; between
    families ~0. There is no population structure (single frequency set).
    """
    nchr = len(chrom_sizes)
    freqs = [rng.uniform(0.1, 0.9, m) for m in chrom_sizes]
    rows = []
    for _ in range(n_fam):
        phap = [ar1_haps(rng, np.tile(freqs[c], (4, 1)), rho) for c in range(nchr)]
        rows.extend(_sib_genome(rng, phap, nchr) for _ in range(sibs))
    chrom, pos = _positions(chrom_sizes)
    return np.array(rows), chrom, pos


def simulate_admixture(rng, chrom_sizes, n_indiv, fst=0.15, rho=0.6,
                       families=False, sibs=4):
    """Two ancestral populations with continuous per-individual admixture.

    ``families=False`` gives unrelated admixed individuals (a low-rank admixture
    axis). ``families=True`` gives sibships whose parents share a family
    admixture proportion (endogamy) -> admixture axis PLUS relatedness. Returns
    ``(G, chrom, pos)``.
    """
    nchr = len(chrom_sizes)
    p1, p2 = zip(*[bn_freqs(rng, m, fst) for m in chrom_sizes])
    rows = []
    if not families:
        for _ in range(n_indiv):
            ai = rng.uniform(0.0, 1.0)
            ind = []
            for c in range(nchr):
                freq = ai * p1[c] + (1 - ai) * p2[c]
                h = ar1_haps(rng, np.tile(freq, (2, 1)), rho)
                ind.append(h[0] + h[1])
            rows.append(np.concatenate(ind))
    else:
        for _ in range(n_indiv // sibs):
            ai = rng.uniform(0.0, 1.0)
            phap = [ar1_haps(rng, np.tile(ai * p1[c] + (1 - ai) * p2[c], (4, 1)), rho)
                    for c in range(nchr)]
            rows.extend(_sib_genome(rng, phap, nchr) for _ in range(sibs))
    chrom, pos = _positions(chrom_sizes)
    return np.array(rows), chrom, pos
